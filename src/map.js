    #getLayoutToBackground(layout) {
        let walls = [];

        for (let y = 0; y < layout.length; y++) {
            let row = [];
            for (let x = 0; x < layout[y].length; x++) {
                let value = -1;
                switch (layout[y][x]) {
                    case 0:
                        value = 93;
                        break;
                    case 1:
                        value = 85;
                        if (y+1 >= layout.length || (y+1 < layout.length && layout[y+1][x] === 0)) {
                            value = 62;
                        }
                        break;
                }
                row.push(value);
            }
            walls.push(row);
        }

        return walls;
    }

    #getLayoutToShadow(layout) {
        let walls = [];

        for (let y = 0; y < layout.length; y++) {
            let row = [];
            for (let x = 0; x < layout[y].length; x++) {
                let value = -1;
                switch (layout[y][x]) {
                    case 0:
                        if (y > 0) {
                            if (layout[y-1][x] === 1) {
                                value = 100;
                            }
                        }
                        break;
                }
                row.push(value);
            }
            walls.push(row);
        }

        return walls;
    }
